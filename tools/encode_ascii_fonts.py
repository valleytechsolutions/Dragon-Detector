"""Native pixel fonts and the supplied octopus expressed as ASCII characters.

Unscii-8's ASCII glyphs are public domain / CC0 (see CREDITS.md). Nearest
neighbour conversion keeps hard pixel edges. No runtime image or font scaling.
"""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'hardware/spotpear/lib/lvgl/scripts/built_in_font/unscii-8.ttf'
font = ImageFont.truetype(str(SOURCE), 8)

def emit(name, width, height, chars):
    data = []
    glyphs = [(0, 0, 0, 0, 0, 0)]
    for char in chars:
        cell = Image.new('L', (8, 8))
        ImageDraw.Draw(cell).text((0, 0), char, font=font, fill=255)
        cell = cell.resize((width, height), Image.Resampling.NEAREST)
        bits = [int(p >= 128) for p in cell.tobytes()]
        bits += [0] * (-len(bits) % 8)
        offset = len(data)
        data.extend(sum(bits[i+j] << (7-j) for j in range(8)) for i in range(0,len(bits),8))
        glyphs.append((offset, width*16, width, height, 0, 0))
    out = [f'static const uint8_t {name}_bitmap[]={{']
    out += [','.join(str(v) for v in data[i:i+32])+',' for i in range(0,len(data),32)]
    out += ['};', f'static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[]={{']
    out += ['{'+f'.bitmap_index={o},.adv_w={a},.box_w={w},.box_h={h},.ofs_x={x},.ofs_y={y}'+'},' for o,a,w,h,x,y in glyphs]
    out += ['};', f'static const uint16_t {name}_unicode[]={{'+','.join(str(ord(c)-ord(chars[0])) for c in chars)+'};']
    out += [f'static const lv_font_fmt_txt_cmap_t {name}_map[]='+
            '{{'+f'.range_start={ord(chars[0])},.range_length={ord(chars[-1])-ord(chars[0])+1},.glyph_id_start=1,.unicode_list={name}_unicode,.glyph_id_ofs_list=NULL,.list_length={len(chars)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY'+'}};']
    out += [f'static lv_font_fmt_txt_glyph_cache_t {name}_cache;',
            f'static const lv_font_fmt_txt_dsc_t {name}_dsc='+
            '{'+f'.glyph_bitmap={name}_bitmap,.glyph_dsc={name}_glyphs,.cmaps={name}_map,.kern_dsc=NULL,.kern_scale=0,.cmap_num=1,.bpp=1,.kern_classes=0,.bitmap_format=0,.cache=&{name}_cache'+'};',
            f'const lv_font_t dragon_ascii_{name}='+
            '{'+f'.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height={height},.base_line=0,.subpx=LV_FONT_SUBPX_NONE,.underline_position=-1,.underline_thickness=1,.dsc=&{name}_dsc,.fallback=LV_FONT_DEFAULT'+'};']
    return out

lines = ['// Generated by tools/encode_ascii_fonts.py. Unscii-8 ASCII: public domain / CC0.',
         '// Source SHA-256: '+hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
         '#include <lvgl.h>', '#ifndef BOARD_RADAR_LITE']
for condition, sizes in [
    ('#if defined(BOARD_AMOLED_175C) || defined(BOARD_AMOLED_175) || defined(BOARD_STOPWATCH)', [(4,6),(8,16),(10,20),(13,26),(23,46)]),
    ('#elif defined(BOARD_XIAO_ROUND)', [(2,3),(4,8),(6,12),(7,14),(12,24)]),
    ('#else', [(3,5),(6,12),(8,16),(10,20),(18,36)])]:
    lines.append(condition)
    for name, (w,h) in zip(('micro','small','body','heading','digits'),sizes):
        lines += emit(name,w,h,'-.0123456789:' if name=='digits' else ''.join(chr(i) for i in range(32,127)))
lines += ['#endif','#endif']
(ROOT/'firmware/src/ascii_fonts.c').write_text('\n'.join(lines)+'\n',encoding='utf8')

# Sample the supplied pink strokes into character cells. Keep the source intact.
source = Image.open(ROOT/'media/theme-logos/octosec.webp').convert('RGB')
mask = Image.new('L', source.size)
mask.putdata([255 if r>65 and r>g*1.7 and r>b*1.15 else 0 for r,g,b in source.getdata()])
mask = mask.crop(mask.getbbox()).resize((36,23),Image.Resampling.BOX)
rows = [''.join('#' if mask.getpixel((x,y))>45 else ' ' for x in range(36)) for y in range(23)]
(ROOT/'firmware/src/octopig_art.inc').write_text('// Generated ASCII rendition of the supplied octopus; see CREDITS.md.\nstatic const char* const OctoAscii[]={\n'+''.join('  "'+row+'",\n' for row in rows)+'};\n',encoding='utf8')
print('Generated five native ASCII font sizes per board and the octopus character grid.')
