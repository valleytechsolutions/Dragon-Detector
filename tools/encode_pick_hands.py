"""Triangulate native vector silhouettes traced from the supplied Reaper references.

Coordinates are (distance from arbor, lateral offset). Widths are slightly
expanded for legibility on 240px panels. Original reference photos are retained.
"""
from pathlib import Path
profiles={
 'McTickler':[(-20,7),(-14,-7),(75,-7),(81,-6),(87,-2),(92,0),(98,-1),(115,-1),(121,-2),(128,-2),(135,0),(139,2),(140,3),(137,4),(132,2),(126,1),(121,2),(119,4),(117,3),(103,3),(94,5),(87,7)],
 'ShortHook':[(-17,8),(-13,-8),(42,-8),(47,-6),(50,-2),(56,0),(75,0),(91,0),(97,-2),(102,-5),(106,-5),(107,-3),(103,1),(98,4),(94,5),(74,5),(56,5),(51,7),(47,8)],
}
def cross(a,b,c):return (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])
def triangulate(points):
    if sum(a[0]*b[1]-b[0]*a[1] for a,b in zip(points,points[1:]+points[:1]))<0:points.reverse()
    indices=list(range(len(points)));triangles=[]
    while len(indices)>3:
        found=False
        for k in range(len(indices)):
            a,b,c=indices[k-1],indices[k],indices[(k+1)%len(indices)]
            if cross(points[a],points[b],points[c])<=0:continue
            if any(all(cross(points[v],points[w],points[i])>=0 for v,w in [(a,b),(b,c),(c,a)]) for i in indices if i not in (a,b,c)):continue
            triangles.append((a,b,c));indices.pop(k);found=True;break
        assert found,'Invalid/self-intersecting pick contour'
    triangles.append(tuple(indices));return triangles
lines=['// Generated by tools/encode_pick_hands.py from the supplied Reaper silhouettes.']
for name,points in profiles.items():
    tris=triangulate(points)
    lines.append('static const lv_point_t pick'+name+'[]={'+','.join('{%d,%d}'%p for p in points)+'};')
    lines.append('static const uint8_t pick'+name+'Triangles[][3]={'+','.join('{%d,%d,%d}'%t for t in tris)+'};')
Path(__file__).resolve().parents[1].joinpath('firmware/src/pick_hands.inc').write_text('\n'.join(lines)+'\n')
print('Validated and triangulated both Reaper silhouettes.')
