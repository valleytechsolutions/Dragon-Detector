"""Build compact, native-size LVGL 8 digit fonts from bundled Montserrat.

Only the twelve characters used by HH:MM / --:-- are included. Pillow is a
build-time dependency; firmware uses ordinary 4-bit LVGL glyphs in flash.
The source font and generated glyph data retain SIL OFL 1.1, see CREDITS.md.
"""
from pathlib import Path
import hashlib
from PIL import Image, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'hardware/spotpear/lib/lvgl/scripts/built_in_font/Montserrat-Medium.ttf'
CHARS='-0123456789:'

def generate(size,resolution):
    font=ImageFont.truetype(str(SOURCE),size)
    boxes=[font.getbbox(c,anchor='ls') for c in CHARS]
    top=min(b[1] for b in boxes);bottom=max(b[3] for b in boxes)
    height=bottom-top+4;baseline=bottom+2
    data=[];glyphs=[(0,0,0,0,0,0)]
    for c,(left,y,right,bottom_glyph) in zip(CHARS,boxes):
        w,h=right-left,bottom_glyph-y
        image=Image.new('L',(w,h))
        ImageDraw.Draw(image).text((-left,-y),c,font=font,fill=255,anchor='ls')
        # Row bits continue directly into the next row in LVGL's font format.
        pixels=[(v*15+127)//255 for v in image.tobytes()]
        if len(pixels)%2:pixels.append(0)
        offset=len(data);data.extend((pixels[i]<<4)|pixels[i+1] for i in range(0,len(pixels),2))
        advance=round(font.getlength(c)*16)
        assert 0<=offset<1<<20 and advance<4096 and w<=255 and h<=255
        assert -128<=left<=127 and -128<=-bottom_glyph<=127
        assert height-baseline-h+bottom_glyph>=0
        glyphs.append((offset,advance,w,h,left,-bottom_glyph))
    # Check every legal minute in both clock formats against the actual layout.
    for hour in range(24):
        for minute in range(60):
            for shown in (hour,hour%12 or 12):
                assert sum(font.getlength(c) for c in f'{shown:02d}:{minute:02d}')<270*resolution/360-8
    lines=['static const uint8_t glyph_bitmap[]={']
    lines += [','.join(f'0x{v:02x}' for v in data[i:i+24])+',' for i in range(0,len(data),24)]
    lines+=['};','static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[]={']
    lines += ['{'+f'.bitmap_index={o},.adv_w={a},.box_w={w},.box_h={h},.ofs_x={x},.ofs_y={y}'+'},' for o,a,w,h,x,y in glyphs]
    lines+=['};',f'#define WATCH_LINE_HEIGHT {height}',f'#define WATCH_BASE_LINE {baseline}']
    print(f'{resolution}px panel: {size}px digits, {len(data)} glyph bytes, {height}px line height')
    return lines

lines=['// Generated by tools/encode_watch_digits.py. Do not hand-edit.',
       '// Copyright 2011 The Montserrat Project Authors; SIL OFL 1.1.',
       '// License: docs/licenses/Montserrat-OFL.txt',
       '// Source SHA-256: '+hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
       '#include <lvgl.h>','#ifndef BOARD_RADAR_LITE']
for condition,size,res in [('#if defined(BOARD_AMOLED_175C) || defined(BOARD_STOPWATCH)',112,466),('#elif defined(BOARD_XIAO_ROUND)',58,240),('#else',86,360)]:
    lines += [condition]+generate(size,res)
lines += ['#endif',
    'static const uint16_t unicode_list[]={'+','.join(str(ord(c)-ord(CHARS[0])) for c in CHARS)+'};',
    'static const lv_font_fmt_txt_cmap_t cmaps[]={{.range_start=45,.range_length=14,.glyph_id_start=1,.unicode_list=unicode_list,.glyph_id_ofs_list=NULL,.list_length=12,.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}};',
    'static lv_font_fmt_txt_glyph_cache_t cache;',
    'static const lv_font_fmt_txt_dsc_t font_dsc={.glyph_bitmap=glyph_bitmap,.glyph_dsc=glyph_dsc,.cmaps=cmaps,.kern_dsc=NULL,.kern_scale=0,.cmap_num=1,.bpp=4,.kern_classes=0,.bitmap_format=0,.cache=&cache};',
    'const lv_font_t dragon_watch_digits={.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=WATCH_LINE_HEIGHT,.base_line=WATCH_BASE_LINE,.subpx=LV_FONT_SUBPX_NONE,.underline_position=-2,.underline_thickness=1,.dsc=&font_dsc};',
    '#endif']
(ROOT/'firmware/src/watch_digits.c').write_text('\n'.join(lines)+'\n',encoding='utf-8')
