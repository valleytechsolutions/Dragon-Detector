"""Encode the supplied portrait as LVGL indexed images readable directly from flash."""
from pathlib import Path
from math import hypot

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def encode(source, size, name):
    portrait = source.resize((size, size), Image.Resampling.LANCZOS)
    # Fade only the round bezel area, keeping both the eagle and the lock in frame.
    mask = Image.new("L", portrait.size)
    mask.putdata([
        round(255 * max(0, min(1, (1 - hypot((x+.5)*2/size-1, (y+.5)*2/size-1)) / .18)))
        for y in range(size) for x in range(size)
    ])
    portrait = Image.composite(portrait, Image.new("RGB", portrait.size, (7, 7, 8)), mask)
    indexed = portrait.quantize(256, method=Image.Quantize.MEDIANCUT)
    palette = indexed.getpalette()
    data = bytearray()
    for r, g, b in zip(palette[::3], palette[1::3], palette[2::3]):
        data.extend((b, g, r, 255))
    data.extend(bytes(1024-len(data)))
    data.extend(indexed.tobytes())
    yield f"static const uint8_t {name}Pixels[] = {{"
    for i in range(0, len(data), 32):
        yield ",".join(map(str, data[i:i+32])) + ","
    yield "};"
    yield f"extern const lv_img_dsc_t {name} = {{{{LV_IMG_CF_INDEXED_8BIT,0,0,{size},{size}}},sizeof({name}Pixels),{name}Pixels}};"


def packed(lines, size):
    """The 466 px portrait is stored deflated (zlib); vladPortraitImage() inflates it into PSRAM."""
    import zlib
    body = [line for line in lines if not line.startswith(("static const", "extern const", "};"))]
    data = bytes(int(x) for x in "".join(body).split(",") if x)
    z = zlib.compress(data, 9)
    assert zlib.decompress(z) == data
    yield f"// {size} px: zlib-deflated indexed portrait ({len(data)} bytes as {len(z)}). vladPortraitImage() inflates it"
    yield "// into PSRAM the first time the theme draws; the pixels are the same."
    yield "#define VLAD_PORTRAIT_PACKED 1"
    yield f"static constexpr size_t vladPortraitBytes = {len(data)};"
    yield "static const uint8_t vladPortraitPacked[] = {"
    for i in range(0, len(z), 32):
        yield ",".join(map(str, z[i:i+32])) + ","
    yield "};"


def main():
    source = Image.open(ROOT / "media/theme-logos/lockpickingvlad-source.jpg").convert("RGB")
    lines = ['// Generated by tools/encode_vlad_art.py.', '#include <lvgl.h>', '#include "board_pins.h"']
    for i, size in enumerate((466, 412, 360, 240)):
        lines.append(("#if" if i == 0 else "#elif") + f" SCREEN_RES >= {size}")
        portrait = list(encode(source, size, "vladPortrait"))
        lines.extend(packed(portrait, size) if size == 466 else portrait)
        lines.extend(encode(source, round(size * .14), "vladSeal"))
    lines.extend(('#else', '#error Unsupported portrait size', '#endif'))
    lines.append(ACCESSOR)
    (ROOT / "firmware/src/vlad_art.cpp").write_text("\n".join(lines) + "\n", encoding="utf8")


ACCESSOR = r'''#ifdef VLAD_PORTRAIT_PACKED
#include <esp_heap_caps.h>
#include "miniz.h"
const lv_img_dsc_t* vladPortraitImage() {
  static lv_img_dsc_t image = {{LV_IMG_CF_INDEXED_8BIT, 0, 0, 466, 466}, 0, nullptr};
  static bool tried = false;
  if (!image.data && !tried) {
    tried = true;  // one attempt: a board without the memory draws the bezel without the portrait
    auto* out = static_cast<uint8_t*>(heap_caps_malloc(vladPortraitBytes, MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT));
    // The decompressor state is about 11 KB: on the heap, not on the UI task's stack.
    auto* state = static_cast<tinfl_decompressor*>(heap_caps_malloc(sizeof(tinfl_decompressor), MALLOC_CAP_8BIT));
    if (out && state) {
      tinfl_init(state);
      size_t in = sizeof(vladPortraitPacked), length = vladPortraitBytes;
      const tinfl_status status = tinfl_decompress(state, vladPortraitPacked, &in, out, out, &length,
                                                   TINFL_FLAG_PARSE_ZLIB_HEADER | TINFL_FLAG_USING_NON_WRAPPING_OUTPUT_BUF);
      if (status == TINFL_STATUS_DONE && length == vladPortraitBytes) {
        image.data = out;
        image.data_size = vladPortraitBytes;
        out = nullptr;
      }
    }
    heap_caps_free(state);
    heap_caps_free(out);
  }
  return image.data ? &image : nullptr;
}
#else
const lv_img_dsc_t* vladPortraitImage() { return &vladPortrait; }
#endif'''


if __name__ == "__main__":
    main()
