"""Encode the owner-supplied PNG as small RGB565+alpha LVGL assets.

The source PNG remains unchanged. Only transparent padding is excluded from
the display bounds; both native sizes are generated to avoid runtime scaling.
Requires Pillow. This is a build-time asset conversion, not a firmware dependency.
"""
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
source=Image.open(root/'media/BWM1-official.png').convert('RGBA')
source=source.crop(source.getbbox())
lines=['// Generated by tools/encode_radar_logo.py; owner-supplied BWM1 logo.', '#include <lvgl.h>', '#include "board_pins.h"']
for resolution,height in [(466,57),(360,44)]:
    width=round(source.width*height/source.height)
    icon=source.resize((width,height),Image.Resampling.LANCZOS)
    pixels=[]
    for r,g,b,a in icon.getdata():
        value=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
        pixels.extend([value>>8,value&255,a])
    lines.append('#if SCREEN_RES >= 466' if resolution==466 else '#else')
    lines.append('static const uint8_t radarLogoPixels[]={')
    lines.extend(','.join(str(v) for v in pixels[i:i+36])+',' for i in range(0,len(pixels),36))
    lines.extend(['};',f'extern const lv_img_dsc_t radar_logo = {{{{LV_IMG_CF_TRUE_COLOR_ALPHA,0,0,{width},{height}}},sizeof(radarLogoPixels),radarLogoPixels}};'])
lines.append('#endif')
(root/'firmware/src/radar_logo.cpp').write_text('\n'.join(lines)+'\n',encoding='utf8')
print('Encoded 39x44 and 51x57 native logo assets; PNG retained unchanged.')
