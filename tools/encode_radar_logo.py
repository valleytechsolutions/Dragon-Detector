"""Encode supplied, unchanged PNGs as small RGB565+alpha LVGL assets.

The source PNG remains unchanged. Only transparent padding is excluded from
the display bounds; all native sizes are generated to avoid runtime scaling.
Requires Pillow. This is a build-time asset conversion, not a firmware dependency.
"""
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
logos=[('radar_logo','media/BWM1-official.png'),
       ('radar_logo_valleytech','media/theme-logos/valleytech.png'),
       ('radar_logo_biscuit','media/theme-logos/biscuit-shop.png'),
       ('radar_logo_marauder','media/theme-logos/jcmk.png')]
lines=['// Generated by tools/encode_radar_logo.py; supplied artwork, see CREDITS.md.', '#include <lvgl.h>', '#include "board_pins.h"']
for name,path in logos:
    source=Image.open(root/path).convert('RGBA')
    source=source.crop(source.getbbox())
    if name!='radar_logo':lines.append('#ifndef BOARD_RADAR_LITE')
    for resolution,height in [(466,57),(360,44),(240,29)]:
        width=round(source.width*height/source.height)
        assert width<=height*2,'Logo exceeds radar header bounds'
        icon=source.resize((width,height),Image.Resampling.LANCZOS)
        pixels=[]
        for r,g,b,a in icon.getdata():
            value=((r>>3)<<11)|((g>>2)<<5)|(b>>3)
            pixels.extend([value>>8,value&255,a])
        lines.append('#if SCREEN_RES >= 466' if resolution==466 else '#elif SCREEN_RES >= 360' if resolution==360 else '#else')
        lines.append(f'static const uint8_t {name}_pixels[]={{')
        lines.extend(','.join(str(v) for v in pixels[i:i+36])+',' for i in range(0,len(pixels),36))
        lines.extend(['};',f'extern const lv_img_dsc_t {name} = {{{{LV_IMG_CF_TRUE_COLOR_ALPHA,0,0,{width},{height}}},sizeof({name}_pixels),{name}_pixels}};'])
    lines.append('#endif')
    if name!='radar_logo':lines.append('#endif')
(root/'firmware/src/radar_logo.cpp').write_text('\n'.join(lines)+'\n',encoding='utf8')
print('Encoded four logos at 240/360/466 panel sizes; original PNGs retained unchanged.')
