"""Convert the unchanged owner PNG into centered stock badge assets (Pillow).

Fit the visible silhouette to the round display, with a 4% edge margin. RLE
RGB565 keeps the firmware asset small; the browser uses the same rendered PNG.
"""
from pathlib import Path
from itertools import groupby
import math, struct
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
source = Image.open(ROOT / 'media/BWM1-official.png').convert('RGBA')
source = source.crop(source.getbbox())
radius = max(math.hypot(x + .5 - source.width / 2, y + .5 - source.height / 2)
             for y in range(source.height) for x in range(source.width)
             if source.getpixel((x, y))[3] >= 128)
lines = ['// Generated by tools/encode_badge_logo.py from the owner-supplied PNG.',
         '#include "board_pins.h"', '#include <stdint.h>', '#include <stddef.h>',
         '#ifndef BOARD_RADAR_LITE']
for size in (480, 466, 412, 360, 240):
    scale = size * .48 / radius
    logo = source.resize((round(source.width * scale), round(source.height * scale)), Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', (size, size), 'black')
    canvas.alpha_composite(logo, ((size - logo.width) // 2, (size - logo.height) // 2))
    rgb = canvas.convert('RGB')
    values = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in rgb.getdata()]
    runs = []
    decoded = []
    for value, group in groupby(values):
        count = sum(1 for _ in group)
        while count:
            n = min(count, 65535); runs.extend((n, value)); decoded.extend([value] * n); count -= n
    assert decoded == values
    lines += [f'#if SCREEN_RES == {size}', 'static const uint16_t stockRuns[] = {']
    lines += [','.join(str(v) for v in runs[i:i+24]) + ',' for i in range(0, len(runs), 24)]
    lines += ['};', '#endif']
    rgb.save(ROOT / f'web/assets/bwm-badge-{size}.png')
    (ROOT / '.work').mkdir(exist_ok=True)
    (ROOT / f'.work/bwm-badge-{size}.ddb').write_bytes(b'DDB1' + struct.pack('<HH', size, size) + b''.join(struct.pack('>H', v) for v in values))
    print(f'{size}: {len(runs)*2} compressed bytes')
lines += ['bool badgeStockPixels(uint8_t* output,size_t bytes){',
          '  if(!output || bytes!=SCREEN_RES*SCREEN_RES*2)return false;',
          '  size_t at=0;',
          '  for(size_t i=0;i<sizeof(stockRuns)/sizeof(stockRuns[0]);i+=2){',
          '    for(unsigned n=0;n<stockRuns[i];++n){',
          '      if(at+2>bytes)return false;',
          '      output[at++]=stockRuns[i+1]>>8;output[at++]=stockRuns[i+1]&255;',
          '    }', '  }', '  return at==bytes;', '}', '#endif']
(ROOT / 'firmware/src/badge_stock.cpp').write_text('\n'.join(lines)+'\n', encoding='utf8')
