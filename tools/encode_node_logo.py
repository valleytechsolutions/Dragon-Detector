"""Encode the centre logos of the wardriving node screens.

The Biscuit Shop and JustCallMeKoko marks are white line art, so each is stored
as plain 8-bit coverage (LV_IMG_CF_ALPHA_8BIT). That format is drawn straight
from flash on every board, including the M5Dial which has no PSRAM, and the
screen paints it white on black. One native size per panel class; nothing is
scaled on the device.

Run with Pillow installed: python tools/encode_node_logo.py
"""
from pathlib import Path
import hashlib, zlib
from PIL import Image

root = Path(__file__).resolve().parents[1]
# (symbol, source artwork, crop to the drawn mark)
logos = [
    ("node_logo_biscuit", "media/theme-logos/biscuit-shop.png", False),
    ("node_logo_jcmk", "media/theme-logos/jcmk.png", True),
]
# Panel class -> logo height in pixels. Watcher (412) uses the 360 art and
# CrowPanel (480) the 466 art, the same split as the theme logos.
heights = [(466, 168), (360, 130), (240, 86)]


def coverage(path: Path, crop: bool) -> Image.Image:
    """White-on-anything artwork as one channel: 255 where the mark is solid."""
    image = Image.open(path)
    if image.mode in ("RGBA", "LA"):
        rgba = image.convert("RGBA")
        luma, alpha = rgba.convert("L"), rgba.getchannel("A")
        mask = Image.composite(luma, Image.new("L", image.size, 0), alpha)
    else:
        mask = image.convert("L")
    if crop:
        # Keep the soft edge of the strokes: crop a little outside the solid mark.
        left, top, right, bottom = mask.point(lambda v: 255 if v > 24 else 0).getbbox()
        margin = max(2, round(max(right - left, bottom - top) * 0.012))
        mask = mask.crop((max(0, left - margin), max(0, top - margin), min(mask.width, right + margin), min(mask.height, bottom + margin)))
    return mask


def main() -> None:
    lines = [
        "// Generated by tools/encode_node_logo.py; supplied artwork, see CREDITS.md.",
        "// Centre logos of the BISCUIT NODE and JCMK Node screens as 8-bit coverage.",
        "#include <lvgl.h>",
        '#include "board_pins.h"',
    ]
    for name, source, crop in logos:
        path = root / source
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        mask = coverage(path, crop)
        lines.append(f"// {name}: {source} sha256 {digest}")
        for resolution, height in heights:
            width = round(mask.width * height / mask.height)
            # The logo sits on the centre line of a round panel with text above and below.
            assert width <= height and height <= resolution * 0.37, "Node logo too large for its panel"
            pixels = mask.resize((width, height), Image.Resampling.LANCZOS).tobytes()
            assert len(pixels) == width * height and max(pixels) >= 250, "Node logo lost its solid areas"
            lines.append("#if SCREEN_RES >= 466" if resolution == 466 else "#elif SCREEN_RES >= 360" if resolution == 360 else "#else")
            lines.append(f"// {width}x{height} CRC32 {zlib.crc32(pixels):08x}")
            lines.append(f"static const uint8_t {name}_map[]={{")
            lines.extend(",".join(str(v) for v in pixels[i:i + 40]) + "," for i in range(0, len(pixels), 40))
            lines.append("};")
            lines.append(f"extern const lv_img_dsc_t {name};")
            lines.append(f"const lv_img_dsc_t {name}={{{{LV_IMG_CF_ALPHA_8BIT,0,0,{width},{height}}},{width * height},{name}_map}};")
        lines.append("#endif")
        # LVGL's alpha-only images use native dimensions; the knob launcher has a 120px canvas.
        width = round(mask.width * 98 / mask.height)
        pixels = mask.resize((width, 98), Image.Resampling.LANCZOS).tobytes()
        symbol = name + "_launcher"
        lines.extend(["#ifdef BOARD_WAVESHARE_P4_KNOB", f"static const uint8_t {symbol}_map[]={{"])
        lines.extend(",".join(str(v) for v in pixels[i:i+40])+"," for i in range(0,len(pixels),40))
        lines.extend(["};", f"extern const lv_img_dsc_t {symbol};",
                      f"const lv_img_dsc_t {symbol}={{{{LV_IMG_CF_ALPHA_8BIT,0,0,{width},98}},{len(pixels)},{symbol}_map}};", "#endif"])
    (root / "firmware/src/node_logo.cpp").write_text("\n".join(lines) + "\n", encoding="utf8")
    print(f"Encoded {len(logos)} node logos at 240/360/466 panel sizes; original artwork unchanged.")


if __name__ == "__main__":
    main()
