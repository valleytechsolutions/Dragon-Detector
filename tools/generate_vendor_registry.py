"""Build a reproducible, flash-only MA-L vendor index from IEEE registry facts.

Input is an explicitly supplied official CSV, never a BLE firmware's code/data.
The source SHA256 and snapshot counts accompany every generated index.
"""
import argparse,csv,hashlib,json,zlib
from lz_block import pack
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
def generate(path):
    raw=path.read_bytes();rows={}
    for row in csv.DictReader(raw.decode('utf-8-sig').splitlines()):
        if row['Registry']!='MA-L':continue
        key=int(row['Assignment'],16);name=row['Organization Name'].strip()
        assert 0<=key<=0xffffff and name and '\0' not in name
        rows.setdefault(key,set()).add(name)
    collisions=sum(len(v)>1 for v in rows.values())
    rows={k:' / '.join(sorted(v)) for k,v in rows.items()}
    assert len(rows)>30000
    names=sorted(set(rows.values()));pool=bytearray();offsets={}
    for name in names:offsets[name]=len(pool);pool.extend(name.encode('utf-8')+b'\0')
    assert len(pool)<1<<24
    index=bytearray()
    for key,name in sorted(rows.items()):index+=key.to_bytes(3,'big')+offsets[name].to_bytes(3,'little')
    def array(name,data):
        return 'static const unsigned char '+name+'[]={\n'+''.join(','.join(str(b) for b in data[i:i+32])+',\n' for i in range(0,len(data),32))+'};\n'
    out=ROOT/'firmware/include/vendor_registry_data.inc'
    packed=pack(index+pool)
    constants=f'static constexpr size_t VendorIndexBytes={len(index)},VendorNamesBytes={len(pool)};\nstatic constexpr uint32_t VendorCrc=0x{zlib.crc32(index+pool):08x};\n'
    out.write_bytes(('// Generated by tools/generate_vendor_registry.py. Registry facts; see docs/VENDOR-REGISTRY.md.\n'+constants+array('vendorPacked',packed)).encode('ascii'))
    metadata={'source':'https://standards-oui.ieee.org/oui/oui.csv','source_sha256':hashlib.sha256(raw).hexdigest(),'prefix_bits':24,'entries':len(rows),'organization_labels':len(names),'shared_prefixes':collisions,'index_bytes':len(index),'names_bytes':len(pool),'generated_sha256':hashlib.sha256(out.read_bytes()).hexdigest()}
    metadata['compressed_bytes']=len(packed)
    (ROOT/'docs/vendor-registry.json').write_bytes((json.dumps(metadata,indent=2)+'\n').encode('utf-8'))
    print(json.dumps(metadata))
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('csv',type=Path);generate(p.parse_args().csv)
